import { test, expect } from '@playwright/test'

// Opt-in, read-only verification against a connected NP1. No file paths or media are published.
test('actual finalized MP4 metadata, HTTP Range and native timestamp seek',async({page,request})=>{
 test.skip(process.env.NCC_PLAYBACK_HARDWARE!=='1','Set NCC_PLAYBACK_HARDWARE=1 for read-only actual-device verification.')
 test.setTimeout(120000)
 const response=await request.get('/api/v1/recordings')
 expect(response.status()).toBe(200)
 const catalog=(await response.json()).data
 expect(catalog.clips.length).toBeGreaterThan(0)
 const front=catalog.clips.find((clip:any)=>clip.camera==='front'&&clip.durationSeconds>15)
 expect(front).toBeTruthy()
 expect(front.videoCodec).toMatch(/^avc[13]$/)
 expect(front.audioCodec).toBe('mp4a')
 expect(front.audioSampleRate).toBe(48000)
 expect(front.audioChannels).toBe(2)
 const stream='/api/v1/recordings/'+encodeURIComponent(front.id)+'/stream'
 const head=await request.get(stream,{headers:{Range:'bytes=0-31'}})
 expect(head.status()).toBe(206)
 expect(head.headers()['content-type']).toBe('video/mp4')
 expect(head.headers()['content-range']).toBe(`bytes 0-31/${front.sizeBytes}`)
 expect((await head.body()).subarray(4,8).toString('ascii')).toBe('ftyp')
 const tail=await request.get(stream,{headers:{Range:'bytes=-128'}})
 expect(tail.status()).toBe(206)
 expect((await tail.body()).length).toBe(128)
 const date=new Intl.DateTimeFormat('sv-SE',{timeZone:'Asia/Tokyo',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date(front.startAt))
 const dayResponse=await request.get('/api/v1/recordings?date='+date)
 const day=(await dayResponse.json()).data
 expect(day.clips.every((clip:any)=>Date.parse(clip.startAt)<Date.parse(date+'T24:00:00+09:00')&&Date.parse(clip.endAt)>Date.parse(date+'T00:00:00+09:00'))).toBe(true)
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/#recordings')
 await expect(page.locator('.drive-toolbar')).toBeVisible()
 if(!await page.getByRole('button',{name:date+'、録画'+catalog.days.find((day:any)=>day.date===date).count+'本',exact:true}).isVisible()){
  const mobileCalendar=page.getByRole('button',{name:/カレンダーで日付を選ぶ/})
  if(await mobileCalendar.isVisible())await mobileCalendar.click()
 }
 await page.getByRole('button',{name:date+'、録画'+catalog.days.find((day:any)=>day.date===date).count+'本',exact:true}).click()
 await page.getByRole('button',{name:'前方',exact:true}).click()
 const target=new Date(Date.parse(front.startAt)+7000)
 const time=new Intl.DateTimeFormat('ja-JP',{timeZone:'Asia/Tokyo',hour:'2-digit',minute:'2-digit',second:'2-digit',hourCycle:'h23'}).format(target)
 await page.getByLabel('再生する時刻を指定').fill(time)
 const video=page.locator('.drive-videos video')
 await expect(video).toHaveCount(1)
 await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).readyState),{timeout:45000}).toBeGreaterThanOrEqual(2)
 await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).videoWidth)).toBe(front.width)
 await expect(video).toHaveJSProperty('muted',false)
 await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).currentTime)).toBeGreaterThanOrEqual(7)
 // A decoded frame and advancing playhead distinguish actual playback from loaded metadata.
 await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).getVideoPlaybackQuality().totalVideoFrames)).toBeGreaterThan(0)
 const playedFrom=await video.evaluate(element=>(element as HTMLVideoElement).currentTime)
 await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).currentTime)).toBeGreaterThan(playedFrom+.3)
 await video.evaluate(element=>(element as HTMLVideoElement).pause())
 const cabin=day.clips.find((clip:any)=>clip.camera==='in'&&Date.parse(clip.startAt)<=target.getTime()&&Date.parse(clip.endAt)>target.getTime()+5000)
 expect(cabin).toBeTruthy()
 expect(cabin.videoCodec).toBe('avc1');expect(cabin.audioCodec).toBe('mp4a')
 await page.getByRole('button',{name:'車内',exact:true}).click()
 await page.getByLabel('再生する時刻を指定').fill(time)
 // Filling the same time can be ignored by the browser; native play still verifies cabin decoding.
 await video.evaluate(element=>(element as HTMLVideoElement).play())
 await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).readyState),{timeout:45000}).toBeGreaterThanOrEqual(2)
 await expect(video).toHaveJSProperty('muted',false)
 await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).getVideoPlaybackQuality().totalVideoFrames)).toBeGreaterThan(0)
 await page.getByRole('button',{name:'並べて表示',exact:true}).click()
 await expect(page.locator('.drive-videos video')).toHaveCount(2)
 await expect.poll(()=>page.locator('.drive-videos video').evaluateAll(elements=>elements.every(element=>(element as HTMLVideoElement).getVideoPlaybackQuality().totalVideoFrames>0)),{timeout:45000}).toBe(true)
 expect(await page.locator('.drive-videos video').evaluateAll(elements=>elements.map(element=>(element as HTMLVideoElement).muted))).toEqual([false,true])
 await page.locator('.drive-videos video').first().evaluate(element=>(element as HTMLVideoElement).pause())
 const next=day.clips.find((clip:any)=>clip.camera==='front'&&Date.parse(clip.startAt)>Date.parse(front.startAt)&&Date.parse(clip.endAt)>Date.parse(front.endAt)&&Date.parse(clip.startAt)<=Date.parse(front.endAt)+2000)
 if(next){
  await page.getByRole('button',{name:'前方',exact:true}).click()
  await page.getByLabel('再生する時刻を指定').fill(time)
  await expect(video).toHaveAttribute('src',new RegExp(encodeURIComponent(front.id)+'/stream$'))
  await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
  await video.evaluate(element=>{const media=element as HTMLVideoElement;media.currentTime=media.duration-.15;return media.play()})
  await expect(video).toHaveAttribute('src',new RegExp(encodeURIComponent(next.id)+'/stream$'),{timeout:15000})
  await expect.poll(()=>video.evaluate(element=>(element as HTMLVideoElement).getVideoPlaybackQuality().totalVideoFrames)).toBeGreaterThan(0)
  await video.evaluate(element=>(element as HTMLVideoElement).pause())
 }
 expect(errors).toEqual([])
})
