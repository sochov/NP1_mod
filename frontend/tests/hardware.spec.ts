import { test, expect } from '@playwright/test'
test('password-free desktop/mobile UI works on a trusted network',async({page,request})=>{
 const response=await request.get('/api/v1/auth/session');expect(response.status()).toBe(200)
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await expect(page.locator('input[type=password]')).toHaveCount(0)
 await expect(page.locator('.sidebar nav a.active')).toHaveText('ダッシュボード')
 await expect(page.getByText('実機データ受信中')).toBeVisible()
 await expect(page.locator('.sidebar > .brand')).toContainText('NP1')
 await expect(page.locator('.owner-avatar')).toHaveCount(0)
 await expect(page.locator('.breadcrumb, .page-heading, .nav-search')).toHaveCount(0)
 await expect(page.locator('.sidebar-bottom')).toContainText('実機データ受信中')
 await expect(page.locator('.sidebar-bottom')).toContainText('Tailscale')
 await expect(page.locator('.topbar .connection')).toHaveCount(0)
 await expect(page.locator('.sidebar nav a').first()).toHaveCSS('font-size','14px')
 await page.screenshot({path:'../tmp/ui-dashboard-desktop.png',fullPage:true})
 await page.getByRole('link',{name:'ライブ',exact:true}).click()
 await page.getByRole('combobox',{name:'映像形式'}).selectOption('jpeg')
 await page.getByRole('button',{name:'映像を表示',exact:true}).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await expect(page.getByAltText('ライブカメラ映像')).toBeVisible()
 await expect.poll(()=>page.getByAltText('ライブカメラ映像').evaluate((el:HTMLImageElement)=>el.naturalWidth)).toBe(640)
 await page.getByRole('button',{name:'表示を停止'}).click()
 await page.getByRole('link',{name:'システム',exact:true}).click();await page.getByRole('button',{name:'SDカード',exact:true}).click();await expect(page.locator('.sidebar nav a.active')).toHaveText('システム')
 await expect(page.getByRole('button',{name:'DRIVERECDATA'})).toBeVisible()
 await page.getByRole('link',{name:'走行履歴'}).click();await expect(page.getByRole('heading',{name:'日別の詳細'})).toBeVisible()
 await expect(page.locator('.jc-panel')).toBeVisible()
 await expect(page.getByRole('heading',{name:'電波マップ',exact:true})).toBeVisible()
 await page.getByLabel('電波の指標').selectOption('sinr');await expect(page.getByText('SINR / dB')).toBeVisible()
 await page.screenshot({path:'../tmp/ui-radio-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844});await page.locator('.tabbar').getByRole('link',{name:'ダッシュボード',exact:true}).click()
 await expect(page.locator('.tabbar a.active')).toHaveText('ダッシュボード')
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await expect(page.locator('.sidebar')).toHaveCount(0)
 await page.screenshot({path:'../tmp/ui-dashboard-mobile.png',fullPage:true})
 expect(errors).toEqual([])
 await page.emulateMedia({colorScheme:'dark'})
 await page.screenshot({path:'../tmp/ui-dashboard-dark.png',fullPage:true})
})
